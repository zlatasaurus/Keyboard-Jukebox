// build-mixxx-mapping.mjs — turns DJ_COMMANDS into the Mixxx mapping xml.
// run `npm run mixxx-mapping` after editing src/renderer/js/config/dj-commands.js
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DJ_COMMANDS, MIDI_STATUS_ON, MIDI_STATUS_OFF } from '../src/renderer/js/config/dj-commands.js';

export const MAPPING_FILE = fileURLToPath(new URL('../integrations/mixxx/Keyboard-Jukebox.midi.xml', import.meta.url));
const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(2, '0');

// every command gets wired for note-on AND note-off, the script decides which one it cares about
function control(cmd, status) {
  return `      <!-- ${cmd.hint}: ${cmd.label} -->
      <control>
        <group>[Master]</group>
        <key>KeyboardJukebox.${cmd.id}</key>
        <status>${hex(status)}</status>
        <midino>${hex(cmd.note)}</midino>
        <options><script-binding/></options>
      </control>`;
}

export function buildMappingXml(commands = DJ_COMMANDS) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tools/build-mixxx-mapping.mjs from dj-commands.js. dont hand-edit, regen instead -->
<MixxxControllerPreset mixxxVersion="2.4.0+" schemaVersion="1">
  <info>
    <name>Keyboard Jukebox</name>
    <author>zlatasaurus</author>
    <description>DJ mode for Keyboard Jukebox: hotkeys and typed words from any app control your decks.</description>
  </info>
  <controller id="KeyboardJukebox">
    <scriptfiles>
      <file functionprefix="KeyboardJukebox" filename="Keyboard-Jukebox-scripts.js"/>
    </scriptfiles>
    <controls>
${commands.flatMap(c => [control(c, MIDI_STATUS_ON), control(c, MIDI_STATUS_OFF)]).join('\n')}
    </controls>
    <outputs/>
  </controller>
</MixxxControllerPreset>
`;
}

// only write when run directly, not when a test imports this
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(MAPPING_FILE, buildMappingXml());
  console.log('wrote', MAPPING_FILE);
}
